// oracleURLEnv names a real Oracle server, oracle://user:pass@host:port/service,
// for TestOracleServer (CI runs gvenzl/oracle-free:23-slim). The user's own
// schema receives D2O_* fixture objects, which the test drops again.
const oracleURLEnv = "DALGO2ORACLE_TEST_URL"

var fixtureDDL = []string{
	`CREATE TABLE D2O_CUSTOMERS (
		ID NUMBER(10) CONSTRAINT D2O_PK_CUSTOMERS PRIMARY KEY,
		NAME VARCHAR2(100 CHAR) NOT NULL,
		CREATED DATE DEFAULT SYSDATE,
		CODE VARCHAR2(10) CONSTRAINT D2O_UQ_CODE UNIQUE)`,
	`CREATE TABLE D2O_ORDERS (
		ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT D2O_PK_ORDERS PRIMARY KEY,
		CUST_ID NUMBER(10) CONSTRAINT D2O_FK_CUST REFERENCES D2O_CUSTOMERS (ID) ON DELETE CASCADE,
		AMOUNT NUMBER(10,2) CONSTRAINT D2O_CK_AMOUNT CHECK (AMOUNT > 0),
		NOTE VARCHAR2(20) DEFAULT 'new')`,
	`CREATE INDEX D2O_IX_ORDERS_CUST ON D2O_ORDERS (CUST_ID, AMOUNT DESC)`,
	`CREATE VIEW D2O_V_ORDERS AS SELECT o.ID, c.NAME, o.AMOUNT FROM D2O_ORDERS o JOIN D2O_CUSTOMERS c ON c.ID = o.CUST_ID`,
	`CREATE TABLE D2O_DROPPED (X NUMBER)`,
	`DROP TABLE D2O_DROPPED`, // into the recycle bin, as BIN$...
}

var fixtureCleanup = []string{
	`DROP VIEW D2O_V_ORDERS`,
	`DROP TABLE D2O_ORDERS PURGE`,
	`DROP TABLE D2O_CUSTOMERS PURGE`,
	`DROP TABLE D2O_DROPPED PURGE`,
	`PURGE RECYCLEBIN`,
}

func TestOracleServer(t *testing.T) {
	dsn := os.Getenv(oracleURLEnv)
	if dsn == "" {
		t.Skip(oracleURLEnv + " is not set")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()

	admin := sql.OpenDB(NewConnector(dsn))
	defer func() { _ = admin.Close() }()
	cleanup := func() {
		for _, s := range fixtureCleanup {
			_, _ = admin.ExecContext(ctx, s)
		}
	}
	cleanup()
	t.Cleanup(cleanup)
	for _, s := range fixtureDDL {
		if _, err := admin.ExecContext(ctx, s); err != nil {
			t.Fatalf("fixture %q: %v", s, err)
		}
	}

	d, err := NewDatabase(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = d.Close() }()
	t.Logf("schema %s", d.SchemaName())

	t.Run("ListCollections", func(t *testing.T) {
		refs, err := d.ListCollections(ctx, nil)
		if err != nil {
			t.Fatal(err)
		}
		names := refNames(refs)
		for _, want := range []string{"D2O_CUSTOMERS", "D2O_ORDERS", "D2O_V_ORDERS"} {
			if !slices.Contains(names, want) {
				t.Errorf("missing %s in %v", want, names)
			}
		}
		for _, n := range names {
			if strings.HasPrefix(n, "BIN$") || n == "D2O_DROPPED" {
				t.Errorf("recycle-bin object listed: %s", n)
			}
		}
	})

	t.Run("ListViews", func(t *testing.T) {
		refs, err := d.ListViews(ctx)
		if err != nil {
			t.Fatal(err)
		}
		names := refNames(refs)
		if !slices.Contains(names, "D2O_V_ORDERS") || slices.Contains(names, "D2O_ORDERS") {
			t.Errorf("views %v", names)
		}
	})

	orders := dal.NewRootCollectionRef("D2O_ORDERS", "")
	customers := dal.NewRootCollectionRef("D2O_CUSTOMERS", "")

	t.Run("DescribeCollection", func(t *testing.T) {
		def, err := d.DescribeCollection(ctx, &orders)
		if err != nil {
			t.Fatal(err)
		}
		if !slices.Equal(def.PrimaryKey, []dal.FieldName{"ID"}) {
			t.Errorf("pk %v", def.PrimaryKey)
		}
		fields := map[dal.FieldName]dbschema.FieldDef{}
		for _, f := range def.Fields {
			fields[f.Name] = f
		}
		if f := fields["ID"]; !f.AutoIncrement || f.Nullable || f.Default != nil {
			t.Errorf("ID %+v", f)
		}
		if f := fields["AMOUNT"]; f.Type != dbschema.Decimal || f.Precision == nil || *f.Precision != (dbschema.Precision{Total: 10, Scale: 2}) {
			t.Errorf("AMOUNT %+v", f)
		}
		if f := fields["NOTE"]; f.Default != (dbschema.DefaultLiteral{Value: "'new'"}) || f.Length == nil || *f.Length != 20 {
			t.Errorf("NOTE %+v", f)
		}
		if len(def.ForeignKeys) != 1 || def.ForeignKeys[0].ReferencedCollection != "D2O_CUSTOMERS" ||
			def.ForeignKeys[0].OnDelete != "CASCADE" || def.ForeignKeys[0].Enforcement != dbschema.ForeignKeyEnforcementEnabled {
			t.Errorf("fks %+v", def.ForeignKeys)
		}
		if !hasIndex(def.Indexes, "D2O_IX_ORDERS_CUST", false, "CUST_ID", "AMOUNT") {
			t.Errorf("indexes %+v", def.Indexes)
		}

		cdef, err := d.DescribeCollection(ctx, &customers)
		if err != nil {
			t.Fatal(err)
		}
		cfields := map[dal.FieldName]dbschema.FieldDef{}
		for _, f := range cdef.Fields {
			cfields[f.Name] = f
		}
		if f := cfields["CREATED"]; f.Type != dbschema.Time || f.Default != (dbschema.DefaultCurrentTimestamp{}) {
			t.Errorf("CREATED %+v", f)
		}
		if f := cfields["NAME"]; f.Nullable || *f.Length != 100 {
			t.Errorf("NAME %+v", f)
		}

		view := dal.NewRootCollectionRef("D2O_V_ORDERS", "")
		vdef, err := d.DescribeCollection(ctx, &view)
		if err != nil || len(vdef.Fields) != 3 {
			t.Errorf("view %+v %v", vdef, err)
		}

		missing := dal.NewRootCollectionRef("D2O_NO_SUCH", "")
		if _, err = d.DescribeCollection(ctx, &missing); err == nil || !strings.Contains(err.Error(), "not found") {
			t.Errorf("missing: %v", err)
		}
	})

	t.Run("ListIndexes", func(t *testing.T) {
		idx, err := d.ListIndexes(ctx, &customers)
		if err != nil {
			t.Fatal(err)
		}
		if !hasIndex(idx, "D2O_UQ_CODE", true, "CODE") || len(idx) != 1 {
			t.Errorf("indexes %+v (the primary key's index is left out)", idx)
		}
	})

	t.Run("ListConstraints", func(t *testing.T) {
		cons, err := d.ListConstraints(ctx, &orders)
		if err != nil {
			t.Fatal(err)
		}
		got := map[string]string{}
		for _, c := range cons {
			got[c.Name] = c.Type
		}
		want := map[string]string{"D2O_PK_ORDERS": "primary-key", "D2O_FK_CUST": "foreign-key", "D2O_CK_AMOUNT": "check"}
		for k, v := range want {
			if got[k] != v {
				t.Errorf("constraint %s = %q, want %q (all: %v)", k, got[k], v, got)
			}
		}
		if len(got) != len(want) {
			t.Errorf("unexpected constraints %v", got)
		}
	})

	t.Run("ListReferrers", func(t *testing.T) {
		refs, err := d.ListReferrers(ctx, &customers)
		if err != nil {
			t.Fatal(err)
		}
		if len(refs) != 1 || refs[0].Collection.Name() != "D2O_ORDERS" || !slices.Equal(refs[0].Fields, []dal.FieldName{"CUST_ID"}) {
			t.Errorf("referrers %+v", refs)
		}
	})

	t.Run("read-only transaction refuses an INSERT", func(t *testing.T) {
		var n int
		err := d.QueryReadOnly(ctx, `SELECT COUNT(*) FROM D2O_ORDERS`, nil, func(rows *sql.Rows) error {
			for rows.Next() {
				if err := rows.Scan(&n); err != nil {
					return err
				}
			}
			return nil
		})
		if err != nil {
			t.Fatalf("read: %v", err)
		}
		tx, err := d.BeginReadOnly(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer func() { _ = tx.Rollback() }()
		_, err = tx.ExecContext(ctx, `INSERT INTO D2O_CUSTOMERS (ID, NAME) VALUES (1, 'x')`)
		var oraErr *network.OracleError
		if !errors.As(err, &oraErr) || oraErr.ErrCode != 1456 {
			t.Fatalf("want ORA-01456, got %v", err)
		}
		if err = d.RunReadonlyTransaction(ctx, func(context.Context, dal.ReadTransaction) error { return nil }); err != nil {
			t.Fatalf("RunReadonlyTransaction: %v", err)
		}
	})

	t.Run("a refused login names nothing of the URL", func(t *testing.T) {
		u, err := url.Parse(dsn)
		if err != nil {
			t.Fatal(err)
		}
		bad := *u
		bad.User = url.UserPassword(u.User.Username(), "wrong-pass-0xDEAD")
		_, err = NewDatabase(ctx, bad.String())
		var ce *ConnectionError
		if !errors.As(err, &ce) || ce.Kind != FailureAuthentication {
			t.Fatalf("want an authentication ConnectionError, got %v", err)
		}
		pw, _ := u.User.Password()
		for _, secret := range []string{u.User.Username(), pw, "wrong-pass", u.Hostname(), u.Port(), strings.Trim(u.Path, "/")} {
			if secret != "" && strings.Contains(strings.ToLower(err.Error()), strings.ToLower(secret)) {
				t.Errorf("error %q names %q", err, secret)
			}
		}
		badService := *u
		badService.Path = "/NO_SUCH_SERVICE"
		_, err = NewDatabase(ctx, badService.String())
		if !errors.As(err, &ce) || ce.Kind != FailureService || strings.Contains(err.Error(), "NO_SUCH_SERVICE") {
			t.Fatalf("want a service ConnectionError, got %v", err)
		}
	})
}

func refNames(refs []dal.CollectionRef) []string {
	out := make([]string, len(refs))
	for i, r := range refs {
		out[i] = r.Name()
	}
	return out
}

func hasIndex(idx []dbschema.IndexDef, name string, unique bool, fields ...dal.FieldName) bool {
	for _, ix := range idx {
		if ix.Name == name {
			return ix.Unique == unique && slices.Equal(ix.Fields, fields)
		}
	}
	return false
}
